#!/usr/bin/env node
// Turns supabase/seed_data/catalogue.csv (the reviewed list of services and prices) into supabase/seed_data/catalogue.sql.
// Edit the CSV, never the SQL. The SQL is safe to run more than once: it only adds what is missing, and never changes an existing service or price
// (a price change goes through price_propose / price_decide in ADA Hub, so it keeps its approval and history).
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const text = fs.readFileSync(path.join(root, 'supabase/seed_data/catalogue.csv'), 'utf8');

function parse(s) { // RFC 4180
  const rows = []; let row = [], cell = '', q = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (q) { if (c === '"') { if (s[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}
const [head, ...rows] = parse(text).filter((r) => r.length > 1);
const col = Object.fromEntries(head.map((h, i) => [h, i]));
const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;
const divisions = new Set(['web', 'tech', 'marketing', 'consulting']);
const models = new Set(['fixed', 'hourly', 'monthly', 'per_unit', 'quote_based']);
const seen = new Set();
const values = rows.map((r, n) => {
  const g = (k) => r[col[k]];
  const where = `catalogue.csv row ${n + 2} (${g('name')})`;
  if (!divisions.has(g('division'))) throw new Error(`${where}: unknown division`);
  if (!models.has(g('pricing_model'))) throw new Error(`${where}: unknown pricing model`);
  if (g('summary').length > 500 || !g('summary').trim()) throw new Error(`${where}: summary must be 1-500 characters`);
  const key = g('division') + '|' + g('name').toLowerCase();
  if (seen.has(key)) throw new Error(`${where}: duplicate service in the division`);
  seen.add(key);
  const quoted = g('pricing_model') === 'quote_based';
  if (quoted !== (g('amount') === '')) throw new Error(`${where}: a quote-based service has no price and every other service has one`);
  if (!quoted && !(Number(g('amount')) >= 0)) throw new Error(`${where}: bad amount`);
  if (!['exact', 'from', 'quoted'].includes(g('price_kind'))) throw new Error(`${where}: price_kind must be exact, from or quoted`);
  return `    (${lit(g('division'))}, ${lit(g('category'))}, ${lit(g('name'))}, ${lit(g('summary'))}, ${lit(g('pricing_model'))}, ${lit(g('billing_unit'))}, ${g('amount') === '' ? 'null' : Number(g('amount')).toFixed(2)}, ${lit(g('price_kind'))}, ${lit(g('source'))})`;
});

const sql = `-- GENERATED by scripts/gen-catalogue-sql.mjs from supabase/seed_data/catalogue.csv. Do not edit by hand.
-- ADA Core build step 2: the real services and prices, taken from the price lists the websites publish today (reviewed 5-6 October 2026).
-- ${rows.length} services (${rows.filter((r) => r[col.amount] !== '').length} priced, the rest quote-based). Currency NAD, no VAT (ADA is not VAT registered).
--
-- HOW TO RUN: Supabase SQL editor of the ADA Core project, as the project owner, ONE run. Safe to run again: it only adds what is missing and never
-- touches an existing service or price (change a price in ADA Hub with price_propose / price_decide so it keeps its approval history).
--
-- WHAT IT DOES AND DOES NOT DO
--  * Services are created with status 'approved' - NOT published. Publishing is a separate, deliberate act (build step 4, when the public API exists).
--  * Prices are loaded as version 1, approved, effective today. This is the bootstrap load by the owner: ADA Core has one staff member, and the pricing
--    rule "you cannot approve your own request" would otherwise make the first catalogue impossible. The audit trail records the reason below.
--  * "price_kind": 'from' = the website shows "From N$x" (a starting price; larger work is quoted), loaded with is_starting_price = true (migration 0053);
--    'exact' = a fixed published price. APPLY MIGRATION 0053 BEFORE THIS SCRIPT (it stops with a clear message if it has not been applied).
--  * Quote-based services (no published price) get no price row; they can be put on a quote with a custom price.
begin;
select set_config('ada.reason', 'Initial catalogue load (build step 2): published price lists of 5-6 October 2026, loaded by the owner', true);

do $load$
declare
  r record; v_div uuid; v_svc uuid; v_new int := 0; v_priced int := 0;
begin
  if not exists (select 1 from information_schema.columns where table_name = 'service_prices' and column_name = 'is_starting_price') then
    raise exception 'apply migration 0053_starting_prices first, then run this script again';
  end if;
  for r in select * from (values
${values.join(',\n')}
  ) as t(div, cat, name, summary, model, unit, amount, kind, source)
  loop
    select id into v_div from divisions where key = r.div;
    if v_div is null then raise exception 'division % does not exist', r.div; end if;

    select id into v_svc from services where division_id = v_div and lower(btrim(name)) = lower(btrim(r.name)) and deleted_at is null;
    if v_svc is null then
      insert into services (division_id, name, category, summary, description, pricing_model, billing_unit, show_price, status, approved_at, status_reason)
      values (v_div, r.name, r.cat, r.summary, r.summary, r.model::pricing_model, r.unit, r.model <> 'quote_based', 'approved', now(), 'initial catalogue load')
      returning id into v_svc;
      v_new := v_new + 1;
    end if;

    if r.amount is not null and not exists (select 1 from service_prices where service_id = v_svc) then
      insert into service_prices (service_id, version, amount, currency, effective_from, status, reason, approved_at, decision_note, is_starting_price)
      values (v_svc, 1, r.amount, 'NAD', current_date, 'approved',
              case r.kind when 'from' then 'Published starting price ("from") - ' else 'Published fixed price - ' end || r.source,
              now(), 'initial catalogue load by the owner', r.kind = 'from');
      v_priced := v_priced + 1;
    end if;
  end loop;
  raise notice 'catalogue: % services added, % prices added', v_new, v_priced;
end
$load$;

-- What is in the catalogue now
select d.name as division, count(*) as services, count(*) filter (where (price_on(s.id)).id is not null) as priced,
       count(*) filter (where s.status = 'approved') as approved, count(*) filter (where s.status = 'published') as published
  from services s join divisions d on d.id = s.division_id where s.deleted_at is null group by d.name, d.sort_order order by d.sort_order;
commit;
`;
const out = path.join(root, 'supabase/seed_data/catalogue.sql');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== sql) { console.error('catalogue.sql is out of date: run node scripts/gen-catalogue-sql.mjs'); process.exit(1); }
  console.log(`catalogue.sql is up to date (${rows.length} services)`);
} else { fs.writeFileSync(out, sql); console.log(`catalogue.sql: ${rows.length} services`); }
